SELECT s.id, 'BAJA', (u.fecha_baja AT TIME ZONE 'America/Montevideo')::date, 'MIGRACION'
FROM socios s JOIN usuarios u ON u.id = s.usuario_id WHERE u.fecha_baja IS NOT NULL;
