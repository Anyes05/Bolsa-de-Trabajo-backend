CREATE TABLE socio_historial_suscripcion (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    socio_id BIGINT NOT NULL REFERENCES socios(id),
    tipo VARCHAR(30) NOT NULL CHECK (tipo IN ('ALTA', 'BAJA', 'REINGRESO', 'REINGRESO_PROGRAMADO')),
    fecha DATE NOT NULL,
    estado VARCHAR(20) NOT NULL DEFAULT 'REGISTRADO'
        CHECK (estado IN ('REGISTRADO', 'PENDIENTE', 'APLICADO', 'CANCELADO')),
    registrado_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    origen VARCHAR(20) NOT NULL DEFAULT 'SISTEMA' CHECK (origen IN ('SISTEMA', 'MIGRACION'))
);
CREATE INDEX socio_historial_fecha_idx ON socio_historial_suscripcion (socio_id, fecha DESC, id DESC);
CREATE UNIQUE INDEX socio_reingreso_pendiente_idx ON socio_historial_suscripcion (socio_id)
    WHERE estado = 'PENDIENTE';
