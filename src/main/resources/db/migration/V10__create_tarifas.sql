CREATE TABLE IF NOT EXISTS tarifas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    periodo DATE NOT NULL UNIQUE,
    monto_base NUMERIC(12, 2) NOT NULL CHECK (monto_base > 0),
    fecha_vencimiento DATE NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

ALTER TABLE cuotas
    ADD COLUMN IF NOT EXISTS tarifa_id BIGINT REFERENCES tarifas(id);

CREATE INDEX IF NOT EXISTS cuotas_tarifa_id_idx ON cuotas(tarifa_id);