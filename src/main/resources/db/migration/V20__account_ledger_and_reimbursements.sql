CREATE TABLE reintegros_programados (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    socio_id BIGINT NOT NULL REFERENCES socios(id),
    concepto VARCHAR(200) NOT NULL,
    monto NUMERIC(12, 2) NOT NULL CHECK (monto > 0),
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    desde_periodo DATE NOT NULL
);

CREATE TABLE movimientos_cuenta (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    socio_id BIGINT NOT NULL REFERENCES socios(id),
    cuota_id BIGINT REFERENCES cuotas(id),
    tipo VARCHAR(20) NOT NULL CHECK (tipo IN ('CUOTA', 'REINTEGRO', 'PAGO')),
    concepto VARCHAR(200) NOT NULL,
    monto NUMERIC(12, 2) NOT NULL CHECK (monto > 0),
    fecha DATE NOT NULL,
    fecha_vencimiento DATE,
    metodo_pago VARCHAR(20) CHECK (metodo_pago IN ('EFECTIVO', 'TRANSFERENCIA', 'COBRADOR')),
    referencia VARCHAR(80),
    observaciones TEXT,
    origen VARCHAR(120) UNIQUE,
    CHECK ((tipo = 'PAGO' AND metodo_pago IS NOT NULL AND fecha_vencimiento IS NULL)
        OR (tipo <> 'PAGO' AND metodo_pago IS NULL AND fecha_vencimiento IS NOT NULL))
);

CREATE INDEX movimientos_cuenta_socio_fecha ON movimientos_cuenta(socio_id, fecha, id);
CREATE INDEX reintegros_programados_socio ON reintegros_programados(socio_id);

INSERT INTO movimientos_cuenta(socio_id, cuota_id, tipo, concepto, monto, fecha, fecha_vencimiento, origen)
SELECT socio_id, id, 'CUOTA', 'Cuota ' || to_char(periodo, 'YYYY-MM'), monto, periodo,
       fecha_vencimiento, 'cuota:' || id
FROM cuotas WHERE estado <> 'ANULADA' ORDER BY periodo, id;

INSERT INTO movimientos_cuenta(socio_id, cuota_id, tipo, concepto, monto, fecha, fecha_vencimiento, origen)
SELECT socio_id, id, 'REINTEGRO', 'Timbre / gasto extra previo', monto_timbre, periodo,
       fecha_vencimiento, 'timbre-previo:' || id
FROM cuotas WHERE estado <> 'ANULADA' AND monto_timbre > 0 ORDER BY periodo, id;

INSERT INTO movimientos_cuenta(socio_id, cuota_id, tipo, concepto, monto, fecha, metodo_pago,
                              referencia, observaciones, origen)
SELECT cuota.socio_id, cuota.id, 'PAGO', 'Pago recibido', pago.monto_cobrado, pago.fecha_emision,
       pago.metodo_pago, pago.nro_cobranza_externo, pago.observaciones, 'pago-previo:' || pago.id
FROM pagos pago JOIN cuotas cuota ON cuota.id = pago.cuota_id
WHERE cuota.estado <> 'ANULADA' ORDER BY pago.fecha_emision, pago.id;

INSERT INTO reintegros_programados(socio_id, concepto, monto, desde_periodo)
SELECT socio_id, 'Timbre / gasto extra previo', monto_timbre,
       (date_trunc('month', periodo) + INTERVAL '1 month')::date
FROM (SELECT DISTINCT ON (socio_id) * FROM cuotas ORDER BY socio_id, periodo DESC, id DESC) ultima
WHERE timbre_recurrente AND monto_timbre > 0 AND estado <> 'ANULADA';