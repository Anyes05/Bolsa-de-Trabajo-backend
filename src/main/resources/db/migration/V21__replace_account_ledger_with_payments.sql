INSERT INTO pagos(socio_id, cuota_id, monto_cobrado, fecha_emision, metodo_pago,
                  nro_cobranza_externo, observaciones)
SELECT socio_id, cuota_id, monto, fecha, metodo_pago, referencia, observaciones
FROM movimientos_cuenta
WHERE tipo = 'PAGO'
  AND (origen IS NULL OR origen NOT LIKE 'pago-previo:%')
ORDER BY fecha, id;

CREATE TABLE reintegros (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    socio_id BIGINT NOT NULL REFERENCES socios(id),
    cuota_id BIGINT REFERENCES cuotas(id),
    concepto VARCHAR(200) NOT NULL,
    monto NUMERIC(12, 2) NOT NULL CHECK (monto > 0),
    fecha DATE NOT NULL,
    fecha_vencimiento DATE NOT NULL,
    origen VARCHAR(120) UNIQUE
);

INSERT INTO reintegros(socio_id, cuota_id, concepto, monto, fecha, fecha_vencimiento, origen)
SELECT socio_id, cuota_id, concepto, monto, fecha, fecha_vencimiento, origen
FROM movimientos_cuenta
WHERE tipo = 'REINTEGRO'
ORDER BY fecha, id;

CREATE INDEX pagos_socio_fecha ON pagos(socio_id, fecha_emision, id);
CREATE INDEX reintegros_socio_fecha ON reintegros(socio_id, fecha, id);

